"""Cortex-M4 cost of the estimation path: code size and instruction count.

Builds c/src plus c/target with arm-none-eabi-gcc for a Cortex-M4F, runs the
benchmark on QEMU's mps2-an386 machine with one instruction per translation
block and exec logging, and counts the instructions executed inside the
library functions (jd_*) per call.

QEMU is not cycle accurate. The instruction count is a proxy. A rough cycle
estimate is added by weighting each executed instruction with the Cortex-M4
TRM timings (zero wait state memory, no pipeline effects modelled), so treat
it as an order of magnitude, not a measurement.

    python scripts/count_instructions.py [--budget-instr N]
"""

import argparse
import csv
import json
import math
import re
import shutil
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
C = ROOT / "c"
BUILD = C / "build-m4"
N_BENCH = 200

CFLAGS = ["-mcpu=cortex-m4", "-mthumb", "-mfpu=fpv4-sp-d16", "-mfloat-abi=hard",
          "-O2", "-ffreestanding", "-fno-math-errno", "-std=c99",
          "-Wall", "-Wextra", "-Werror", "-ffunction-sections", "-fdata-sections"]

BENCHES = {1: "jd_mras_step", 2: "jd_emf_step", 3: "jd_det_step"}


def read_vector(path, rows):
    hdr = {}
    data = []
    with open(path) as f:
        for line in f:
            if line.startswith("#"):
                if "=" in line:
                    k, v = line[2:].strip().split("=", 1)
                    hdr[k] = v
                continue
            data.append([float(x) for x in line.split(",")])
            if len(data) >= rows:
                break
    return hdr, data


def write_inputs():
    hm, dm = read_vector(C / "vectors" / "mras_jam.csv", N_BENCH)
    he, _ = read_vector(C / "vectors" / "emf_jam.csv", N_BENCH)
    Ts = float(hm["Ts"])
    R = float(hm["R"])
    L = float(hm["L"])
    p = float(hm["p"])

    def f(x):
        return f"{float(x):.9e}f"

    model = f"{{ {f(Ts)}, {f(R / L)}, {f(math.exp(-R / L * Ts))}, {f(1 / L)} }}"
    lines = [
        "/* generated by scripts/count_instructions.py */",
        "#ifndef BENCH_INPUTS_H", "#define BENCH_INPUTS_H",
        f"#define BENCH_N {N_BENCH}u",
        f"#define BENCH_TH0 {f(hm['th0'])}",
        f"#define BENCH_W0 {f(hm['w0'])}",
        f"#define BENCH_IQ0 {f(hm['iq0'])}",
        f"#define BENCH_PSI {f(hm['psi'])}",
        f"#define BENCH_P {f(p)}",
        f"static const jd_mras_params_t bench_mras = {{ {model}, {f(hm['psi'])}, "
        f"{f(float(hm['psi']) / L)}, {f(hm['op4'])}, {f(float(hm['op5']) * Ts)} }};",
        f"static const jd_emf_params_t bench_emf = {{ {model}, {f(he['op4'])}, {f(he['op5'])}, "
        f"{f(he['op6'])}, {f(float(he['op7']) * Ts)}, {f(he['op8'])} }};",
        f"static const jd_det_params_t bench_det = {{ {int(float(hm['det_n']))}u, "
        f"{f(1 / (float(hm['det_n']) * Ts))}, {f(hm['det_ath'])}, {f(hm['det_wen'])} }};",
        "static const float bench_in[BENCH_N][4] = {",
    ]
    lines += [f"    {{ {f(r[0])}, {f(r[1])}, {f(r[2])}, {f(r[3])} }}," for r in dm]
    lines += ["};", "static const float bench_wm[BENCH_N] = {"]
    lines += [f"    {f(r[5] / p)}," for r in dm]
    lines += ["};", "#endif", ""]
    (BUILD / "bench_inputs.h").write_text("\n".join(lines))


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kw)


def build():
    BUILD.mkdir(exist_ok=True)
    write_inputs()
    gcc = "arm-none-eabi-gcc"
    lib = ["jd_math", "jd_mras", "jd_emf", "jd_detector"]
    objs = []
    for name in lib:
        o = BUILD / f"{name}.o"
        run([gcc, *CFLAGS, "-Wconversion", "-Wdouble-promotion", "-Wshadow",
             "-I", str(C / "include"), "-c", str(C / "src" / f"{name}.c"), "-o", str(o)])
        objs.append(o)
    for name in ["startup", "bench"]:
        o = BUILD / f"{name}.o"
        run([gcc, *CFLAGS, "-I", str(C / "include"), "-I", str(BUILD),
             "-c", str(C / "target" / f"{name}.c"), "-o", str(o)])
        objs.append(o)
    elf = BUILD / "bench.elf"
    run([gcc, *CFLAGS, "-nostdlib", "-T", str(C / "target" / "an386.ld"),
         "-Wl,--gc-sections", *map(str, objs), "-lgcc", "-o", str(elf)])
    return elf, objs[:len(lib)]


def lib_size(objs):
    out = run(["arm-none-eabi-size", "-t", *map(str, objs)]).stdout.splitlines()
    text, data, bss = (int(x) for x in out[-1].split()[:3])
    return {"text": text, "data": data, "bss": bss}


def symbols(elf):
    """Function name -> (start, end), Thumb bit cleared."""
    syms = {}
    for line in run(["arm-none-eabi-nm", "-S", "--defined-only", str(elf)]).stdout.splitlines():
        parts = line.split()
        if len(parts) == 4 and parts[2] in "tT":
            start = int(parts[0], 16) & ~1
            syms[parts[3]] = (start, start + int(parts[1], 16))
    return syms


def disasm(elf):
    """pc -> (mnemonic, operands)."""
    table = {}
    pat = re.compile(r"^\s*([0-9a-f]+):\s+(?:[0-9a-f]{4}\s?){1,2}\s+(\S+)\s*(.*)$")
    for line in run(["arm-none-eabi-objdump", "-d", "--no-show-raw-insn", str(elf)]).stdout.splitlines():
        m = re.match(r"^\s*([0-9a-f]+):\s+(\S+)\s*(.*)$", line)
        if m and not line.rstrip().endswith(">:"):
            table[int(m.group(1), 16)] = (m.group(2), m.group(3))
    return table


def cycles(mn, ops):
    """Rough Cortex-M4 cycle count per instruction (TRM, no wait states)."""
    m = mn.split(".")[0]
    if m in ("vdiv", "vsqrt"):
        return 14
    if m in ("vmla", "vmls", "vnmla", "vnmls", "vfma", "vfms", "vfnma", "vfnms"):
        return 3
    if m in ("udiv", "sdiv"):
        return 12
    if m in ("push", "pop", "ldm", "stm", "ldmia", "stmia", "stmdb", "vpush", "vpop",
             "vldmia", "vstmia", "vldmdb", "vstmdb", "vldm", "vstm"):
        regs = re.search(r"\{(.*)\}", ops)
        n = 0
        if regs:
            for r in regs.group(1).split(","):
                r = r.strip()
                if "-" in r:
                    a, b = r.split("-")
                    n += int(re.sub(r"\D", "", b)) - int(re.sub(r"\D", "", a)) + 1
                elif r:
                    n += 1
        return 1 + max(n, 1)
    if m.startswith(("ldr", "str", "vldr", "vstr")):
        return 2
    if m in ("b", "bl", "bx", "blx", "cbz", "cbnz") or (m.startswith("b") and len(m) == 3):
        return 2
    return 1


def trace(elf):
    qemu = shutil.which("qemu-system-arm")
    if qemu is None:
        sys.exit("qemu-system-arm not found")
    log = BUILD / "exec.log"
    cmd = [qemu, "-M", "mps2-an386", "-nographic", "-monitor", "none", "-serial", "none",
           "-semihosting-config", "enable=on,target=native",
           "-accel", "tcg,one-insn-per-tb=on", "-d", "exec,nochain", "-D", str(log),
           "-kernel", str(elf)]
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
    if "bench done" not in res.stdout + res.stderr or res.returncode != 0:
        sys.exit(f"QEMU run failed ({res.returncode}): {res.stdout} {res.stderr}")
    pcs = []
    pat = re.compile(r"Trace \d+: \S+ \[[0-9a-f]+/([0-9a-f]+)/")
    with open(log) as f:
        for line in f:
            m = pat.match(line)
            if m:
                pcs.append(int(m.group(1), 16))
    return pcs


def count(pcs, syms, dis):
    lib = [(a, b, n) for n, (a, b) in syms.items() if n.startswith("jd_")]
    begin = syms["bench_begin"][0]
    end = syms["bench_end"][0]

    def in_lib(pc):
        return any(a <= pc < b for a, b, _ in lib)

    results = {}
    i = 0
    bench_ids = iter(sorted(BENCHES))
    while i < len(pcs):
        if pcs[i] == begin:
            bid = next(bench_ids)
            n_ins = 0
            n_cyc = 0
            mix = Counter()
            i += 1
            while pcs[i] != end:
                if in_lib(pcs[i]):
                    mn, ops = dis.get(pcs[i], ("?", ""))
                    n_ins += 1
                    n_cyc += cycles(mn, ops)
                    mix[mn.split(".")[0]] += 1
                i += 1
            results[BENCHES[bid]] = {
                "instructions_per_call": n_ins / N_BENCH,
                "cycles_estimate_per_call": n_cyc / N_BENCH,
                "top_instructions": dict(mix.most_common(6)),
            }
        i += 1
    return results


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--budget-instr", type=float, default=None,
                    help="fail if EMF+PLL plus detector exceeds this many instructions")
    args = ap.parse_args()
    elf, objs = build()
    size = lib_size(objs)
    syms = symbols(elf)
    res = count(trace(elf), syms, disasm(elf))
    fn_size = {n: b - a for n, (a, b) in syms.items() if n.startswith("jd_")}
    out = {"target": "Cortex-M4F, arm-none-eabi-gcc -O2, QEMU mps2-an386",
           "calls_per_benchmark": N_BENCH, "library_size_bytes": size,
           "function_size_bytes": fn_size, "per_call": res}
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "m4_cost.json").write_text(json.dumps(out, indent=2) + "\n")

    print(f"library code size: text {size['text']} B, data {size['data']} B, bss {size['bss']} B")
    print(f"{'function':<14} {'instr/call':>10} {'~cycles/call':>13}")
    for name, r in res.items():
        print(f"{name:<14} {r['instructions_per_call']:>10.0f} {r['cycles_estimate_per_call']:>13.0f}")
    for fs in (10e3, 15e3, 20e3):
        budget = 100e6 / fs
        path = res["jd_emf_step"]["cycles_estimate_per_call"] + res["jd_det_step"]["cycles_estimate_per_call"]
        print(f"EMF+PLL + detector at {fs / 1e3:.0f} kHz on a 100 MHz core: "
              f"~{path:.0f} of {budget:.0f} cycles ({100 * path / budget:.0f} %)")
    if args.budget_instr is not None:
        tot = res["jd_emf_step"]["instructions_per_call"] + res["jd_det_step"]["instructions_per_call"]
        if tot > args.budget_instr:
            sys.exit(f"over budget: {tot:.0f} > {args.budget_instr:.0f} instructions")


if __name__ == "__main__":
    main()
