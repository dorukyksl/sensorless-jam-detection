"""Run the full benchmark and write results/benchmark.json and results/summary.md.

    python scripts/run_benchmark.py            # full protocol, a few minutes
    python scripts/run_benchmark.py --quick    # small sets, for CI
"""

import argparse
import json
import math
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from jamsim.benchmark import Protocol, evaluate_config, summarise        # noqa: E402
from jamsim.sim import OBS_IDEAL, OBS_MRAS, OBS_EMF, OBS_NAMES           # noqa: E402

FS_LIST = (10e3, 15e3, 20e3)
KINDS = (OBS_IDEAL, OBS_MRAS, OBS_EMF)


def _job(args):
    fs, kind, proto = args
    return evaluate_config(fs, kind, proto)


def fmt(x, nd=1):
    return "none" if (x is None or (isinstance(x, float) and math.isnan(x))) else f"{x:.{nd}f}"


def window_label(ms):
    return "single sample" if ms == 0.0 else f"{ms:g} ms"


def write_summary(results, path):
    lines = ["# Benchmark summary", "",
             "Generated by scripts/run_benchmark.py. Synthetic loads, simulation only.", ""]
    for label, title in (("chosen", "Tuned detector (window chosen on the tuning set)"),
                         ("plain", "Threshold on a single sample")):
        lines += [f"## {title}", "",
                  "| fs | observer | bandwidth | window | threshold [krad/s^2] | false alarms on held out normal cutting | jams detected | median jam latency [ms] | snags detected |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for r in results:
            c = r[label]
            ev = c["events"]
            jam = [e for e in ev if e["kind"] == "jam"]
            snag = [e for e in ev if e["kind"] == "snag"]
            lat = sorted(e["latency_ms"] for e in jam if e["detected"])
            med = lat[len(lat) // 2] if lat else math.nan
            bw = "none" if c["bw"] is None else f"{c['bw']:.0f} Hz"
            lines.append(
                f"| {r['fs'] / 1e3:.0f} kHz | {OBS_NAMES[r['observer']]} | {bw} | {window_label(c['window_ms'])} | "
                f"{c['a_th'] / 1e3:.1f} | {c['false_alarm_runs']} of {c['normal_runs']} runs ({c['normal_seconds']:.0f} s) | "
                f"{sum(e['detected'] for e in jam)}/{len(jam)} | {fmt(med)} | "
                f"{sum(e['detected'] for e in snag)}/{len(snag)} |")
        lines.append("")
    lines += ["## Detection rate and latency by severity (tuned detector, 15 kHz)", "",
              "| event | severity [Nm] | " + " | ".join(OBS_NAMES[k] for k in KINDS) + " |",
              "|---|---|" + "---|" * len(KINDS)]
    at15 = {r["observer"]: summarise(r["chosen"]["events"]) for r in results if r["fs"] == 15e3}
    if at15:
        keys = sorted(next(iter(at15.values())).keys(), key=lambda k: (k[0], k[1]))
        for key in keys:
            cells = []
            for k in KINDS:
                s = at15[k][key]
                cells.append(f"{s['rate'] * 100:.0f} % ({fmt(s['median_ms'])} ms)")
            lines.append(f"| {key[0]} | {key[1]:g} | " + " | ".join(cells) + " |")
    lines.append("")
    path.write_text("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--workers", type=int, default=None)
    args = ap.parse_args()
    proto = Protocol(n_normal=6, normal_s=2.0, n_tune=3, n_eval=4) if args.quick else Protocol()
    jobs = [(fs, kind, proto) for fs in FS_LIST for kind in KINDS]
    t0 = time.time()
    with ProcessPoolExecutor(max_workers=args.workers) as ex:
        results = list(ex.map(_job, jobs))
    out = ROOT / "results"
    out.mkdir(exist_ok=True)
    name = "benchmark_quick" if args.quick else "benchmark"
    (out / f"{name}.json").write_text(json.dumps(
        {"protocol": proto.__dict__, "results": results}, indent=1, default=float) + "\n")
    write_summary(results, out / ("summary_quick.md" if args.quick else "summary.md"))
    print(f"done in {time.time() - t0:.0f} s")
    print((out / ("summary_quick.md" if args.quick else "summary.md")).read_text())


if __name__ == "__main__":
    main()
